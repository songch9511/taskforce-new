import { describe, expect, it } from "vitest";

import { resolveDueText } from "./dates";

// 2025-09-22 월요일 오전 10시 (한국 시간)
const monday = new Date("2025-09-22T10:00:00+09:00");
const saturday = new Date("2025-09-27T10:00:00+09:00");

describe("resolveDueText", () => {
  it.each([
    ["금요일까지", "2025-09-26"],
    ["금욜 오전까지", "2025-09-26"],
    ["월요일", "2025-09-22"],
    ["이번 주 목요일", "2025-09-25"],
    ["다음 주 수요일까지", "2025-10-01"],
    ["다음주 월요일", "2025-09-29"],
    ["다다음 주 화요일", "2025-10-07"],
    ["이번 주 안에", "2025-09-26"],
    ["이번주까지", "2025-09-26"],
    ["이번 달 말", "2025-09-30"],
    ["월말까지", "2025-09-30"],
    ["25일까지", "2025-09-25"],
    ["10일까지", "2025-10-10"],
    ["10월 9일", "2025-10-09"],
    ["10/9(목)까지", "2025-10-09"],
    ["내일 오전", "2025-09-23"],
    ["모레", "2025-09-24"],
    ["오늘 중으로", "2025-09-22"],
  ])("%s → %s", (text, expected) => {
    expect(resolveDueText(text, monday)).toBe(expected);
  });

  it("토요일에 말한 '금요일'은 다음 주 금요일이다", () => {
    expect(resolveDueText("금요일까지", saturday)).toBe("2025-10-03");
  });

  it("한국 시간 기준으로 날짜를 센다", () => {
    // UTC로는 9/21 일요일이지만 한국 시간으로는 9/22 월요일
    expect(resolveDueText("내일", new Date("2025-09-21T16:00:00Z"))).toBe("2025-09-23");
  });

  it("12월에 말한 1월 날짜는 다음 해다", () => {
    expect(resolveDueText("1/5까지", new Date("2025-12-20T10:00:00+09:00"))).toBe("2026-01-05");
  });

  it.each(["다음 주 초", "조만간", "3일 안에", "없는 날짜 2월 30일", ""])("모르는 표현은 null: %s", (text) => {
    expect(resolveDueText(text, monday)).toBeNull();
  });
});
